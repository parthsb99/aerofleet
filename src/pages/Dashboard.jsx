export default function Dashboard() {
  const { user } = useContext(AuthContext);
  const navigate  = useNavigate();
  const { dark }  = useTheme();
  const socket    = useSocket();

  const [vehicles, setVehicles] = useState([]);
  const [bookings, setBookings] = useState([]);
  const [expenses, setExpenses] = useState([]);
  const [loading,  setLoading]  = useState(true);

  const headers = { Authorization: `Bearer ${user?.token}`, 'Content-Type': 'application/json' };

  /* Reusable data refresh function */
  const refreshData = useCallback(() => {
    if (!user?.token) return;
    Promise.all([
      fetch(`${API}/api/vehicles`, { headers }).then(r => r.json()).catch(() => []),
      fetch(`${API}/api/bookings`,  { headers }).then(r => r.json()).catch(() => []),
      fetch(`${API}/api/expenses`,  { headers }).then(r => r.json()).catch(() => []),
    ]).then(([v, b, e]) => {
      setVehicles(Array.isArray(v) ? v : []);
      setBookings(Array.isArray(b) ? b : []);
      let eList = Array.isArray(e) ? e : [];
      if (eList.length === 0 && user?._id) {
        try {
          const localSaved = localStorage.getItem(`aerofleet_expenses_${user._id}`);
          if (localSaved) eList = JSON.parse(localSaved);
        } catch (err) {}
      }
      setExpenses(eList);
      setLoading(false);
    });
  }, [user?.token]);

  /* fetch real data */
  useEffect(() => {
    if (!user?.token) { setLoading(false); return; }
    refreshData();
  }, [user, refreshData]);

  /* ── Socket.IO: Auto-refresh dashboard on real-time events ──────────── */
  useEffect(() => {
    if (!socket) return;
    const handleUpdate = () => refreshData();
    socket.on('service:updated', handleUpdate);
    socket.on('expenditure:updated', handleUpdate);
    socket.on('booking:updated', handleUpdate);
    // Also refresh on reconnect to sync any missed events
    socket.on('reconnect', handleUpdate);
    return () => {
      socket.off('service:updated', handleUpdate);
      socket.off('expenditure:updated', handleUpdate);
      socket.off('booking:updated', handleUpdate);
      socket.off('reconnect', handleUpdate);
    };
  }, [socket, refreshData]);

  /* ── computed stats ── */
  const activeVehicles  = vehicles.length;
  const pendingServices = bookings.filter(b => b.status === 'Pending' || b.status === 'In Progress').length;
  const completedBookingSpent = bookings
    .filter(b => b.status === 'Completed')
    .reduce((a, b) => a + (b.cost || b.packageSubtotal || b.packagePrice || 0), 0);
  const manualSpent = expenses
    .filter(e => e.source !== 'service_booking' && !e.bookingId)
    .reduce((a, e) => a + (e.amount || 0), 0);
  const totalSpent = completedBookingSpent + manualSpent;

  /* ── activity feed (real bookings → static fallback) ── */
  const recentBookings = [...bookings]
    .sort((a, b) => new Date(b.createdAt) - new Date(a.createdAt))
    .slice(0, 5);

  const activityEvents = recentBookings.length > 0
    ? recentBookings.map(b => ({
        id:        `booking-${b._id}`,
        icon:      b.status === 'Cancelled' ? '✕' : b.status === 'Completed' ? '✅' : '🔧',
        iconBg:    b.status === 'Completed' ? '#22c55e18' : b.status === 'Cancelled' ? '#ef444418' : '#3b82f618',
        iconColor: b.status === 'Completed' ? '#22c55e'  : b.status === 'Cancelled' ? '#ef4444'   : '#60a5fa',
        text:   'Service',
        bold:   b.serviceType,
        suffix: `booked for ${new Date(b.date).toLocaleDateString('en-IN', { day: 'numeric', month: 'short' })} at ${b.time}.`,
        time:   timeAgo(b.createdAt),
      }))
    : STATIC_EVENTS;

  /* ── stat card data ── */
  const stats = [
    {
      label:      'ACTIVE VEHICLES',
      value:      loading ? '—' : activeVehicles,
      icon:       <TruckIcon />,
      iconBg:     'rgba(37,99,235,0.1)',
      onClick:    () => navigate('/my-vehicles'),
    },
    {
      label:      'PENDING SERVICES',
      value:      loading ? '—' : pendingServices,
      icon:       <WrenchIcon />,
      iconBg:     'rgba(37,99,235,0.1)',
      onClick:    () => navigate('/service-history'),
    },
    {
      label:      'MONTHLY EXPENDITURE',
      value:      totalSpent > 0 ? `₹${(totalSpent / 1000).toFixed(1)}k` : '₹0',
      icon:       <MoneyIcon />,
      iconBg:     'rgba(37,99,235,0.1)',
      onClick:    () => navigate('/expenditure'),
    },
  ];

  /* ─────────────────────── render ─────────────────────── */
  return (
    <div className="r-page-wrap">
      <Sidebar />
      <div className="r-content" style={{ background: dark ? '#0a0a0a' : '#f1f5f9' }}>
        <Topbar />

        <div style={{ flex: 1, overflowY: 'auto', display: 'flex', flexDirection: 'column' }}>
          <div style={{ padding: '20px 32px 20px', display: 'flex', flexDirection: 'column', minHeight: 'calc(100vh - 100px)' }}>

            {/* ── Header ── */}
            <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'flex-end', marginBottom: 18 }}>
              <h1 style={{ fontSize: 28, fontWeight: 800, color: dark ? '#f0f0f0' : '#0f172a', letterSpacing: '-0.03em', margin: 0 }}>
                Fleet Overview
              </h1>
              <div style={{ display: 'flex', alignItems: 'center', gap: 10 }}>
                <button
                  onClick={() => navigate('/book-service')}
                  style={{ marginLeft: 8, padding: '8px 16px', background: '#2563eb', color: '#fff', border: 'none', borderRadius: 7, fontSize: 12, fontWeight: 600, cursor: 'pointer', transition: 'background 0.15s' }}
                  onMouseOver={e => e.currentTarget.style.background = '#3b82f6'}
                  onMouseOut={e  => e.currentTarget.style.background = '#2563eb'}
                >
                  + Book Service
                </button>
              </div>
            </div>

            {/* ── Stat Cards ── */}
            <div style={{ display: 'grid', gridTemplateColumns: 'repeat(3,1fr)', gap: 16, marginBottom: 18 }}>
              {stats.map(s => (
                <div
                  key={s.label}
                  onClick={s.onClick}
                  style={{ background: dark ? '#111111' : '#ffffff', border: `1px solid ${dark ? '#1c1c1c' : '#e2e8f0'}`, borderRadius: 14, padding: '24px 24px', cursor: 'pointer', transition: 'border-color 0.15s, transform 0.15s, box-shadow 0.15s' }}
                  onMouseOver={e => { e.currentTarget.style.borderColor = dark ? '#2a2b30' : '#cbd5e1'; e.currentTarget.style.transform = 'translateY(-2px)'; e.currentTarget.style.boxShadow = '0 10px 28px rgba(0,0,0,0.5)'; }}
                  onMouseOut={e  => { e.currentTarget.style.borderColor = dark ? '#1c1c1c' : '#e2e8f0'; e.currentTarget.style.transform = 'translateY(0)';    e.currentTarget.style.boxShadow = 'none'; }}
                >
                  <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'flex-start', marginBottom: 16 }}>
                    <div style={{ fontSize: 10, fontWeight: 700, color: dark ? '#6b7280' : '#94a3b8', letterSpacing: '0.14em' }}>{s.label}</div>
                    <div style={{ width: 40, height: 40, borderRadius: 10, background: s.iconBg, display: 'flex', alignItems: 'center', justifyContent: 'center' }}>
                      {s.icon}
                    </div>
                  </div>
                  <div style={{ fontSize: 38, fontWeight: 800, color: dark ? '#f0f0f0' : '#0f172a', letterSpacing: '-0.03em', lineHeight: 1 }}>
                    {s.value}
                  </div>
                </div>
              ))}
            </div>

            {/* ── Bottom Row: Map + Activity ── */}
            <div style={{ display: 'grid', gridTemplateColumns: '65fr 35fr', gap: 20, alignItems: 'stretch', flex: 1 }}>

              {/* Live Deployment Map */}
              <AeroFleetMap height={340} />

              {/* System Activity */}
              <div style={{ background: dark ? '#111111' : '#ffffff', border: `1px solid ${dark ? '#1c1c1c' : '#e2e8f0'}`, borderRadius: 14, display: 'flex', flexDirection: 'column', minHeight: 0 }}>
                <div style={{ padding: '16px 22px', borderBottom: `1px solid ${dark ? '#1c1c1c' : '#e2e8f0'}`, display: 'flex', justifyContent: 'space-between', alignItems: 'center', background: dark ? '#0f0f0f' : '#f8fafc', borderRadius: '14px 14px 0 0', flexShrink: 0 }}>
                  <span style={{ fontSize: 15, fontWeight: 700, color: dark ? '#f0f0f0' : '#0f172a' }}>System Activity</span>
                  <span onClick={() => navigate('/service-history')} style={{ fontSize: 11, color: '#3b82f6', cursor: 'pointer', fontWeight: 500 }}>
                    View all →
                  </span>
                </div>

                <div style={{ flex: 1, overflowY: 'auto', padding: '4px 0' }}>
                  {activityEvents.map((ev, i) => (
                    <div
                      key={ev.id}
                      style={{ display: 'flex', gap: 14, padding: '18px 22px', borderBottom: i < activityEvents.length - 1 ? `1px solid ${dark ? '#161616' : '#e2e8f0'}` : 'none', transition: 'background 0.1s', cursor: 'default' }}
                      onMouseOver={e => e.currentTarget.style.background = dark ? '#0f0f0f' : '#f8fafc'}
                      onMouseOut={e  => e.currentTarget.style.background = 'transparent'}
                    >
                      <div style={{ width: 40, height: 40, borderRadius: 10, flexShrink: 0, background: ev.iconBg, border: `1px solid ${ev.iconColor}30`, display: 'flex', alignItems: 'center', justifyContent: 'center', fontSize: 16, color: ev.iconColor }}>
                        {ev.icon}
                      </div>
                      <div style={{ flex: 1, minWidth: 0 }}>
                        <div style={{ fontSize: 12, color: dark ? '#9ca3af' : '#475569', lineHeight: 1.65 }}>
                          {ev.text}{' '}
                          <span style={{ color: dark ? '#f0f0f0' : '#0f172a', fontWeight: 600 }}>{ev.bold}</span>
                          {' '}{ev.suffix}
                        </div>
                        <div style={{ fontSize: 10, color: '#4b5563', marginTop: 5 }}>{ev.time}</div>
                      </div>
                    </div>
                  ))}

                  {/* Quick action */}
                  <div style={{ padding: '18px 22px', borderTop: `1px solid ${dark ? '#1c1c1c' : '#e2e8f0'}`, marginTop: 4 }}>
                    <button
                      onClick={() => navigate('/book-service')}
                      style={{ width: '100%', padding: '12px', background: 'rgba(37,99,235,0.1)', border: '1px solid rgba(37,99,235,0.25)', color: '#60a5fa', borderRadius: 9, fontSize: 12, fontWeight: 600, cursor: 'pointer', transition: 'all 0.15s' }}
                      onMouseOver={e => { e.currentTarget.style.background = 'rgba(37,99,235,0.18)'; e.currentTarget.style.borderColor = 'rgba(37,99,235,0.4)'; }}
                      onMouseOut={e  => { e.currentTarget.style.background = 'rgba(37,99,235,0.1)';  e.currentTarget.style.borderColor = 'rgba(37,99,235,0.25)'; }}
                    >
                      + Schedule Maintenance
                    </button>
                  </div>
                </div>
              </div>
            </div>

          </div>
        </div>
        <AppFooter />
      </div>
    </div>
  );
}

function timeAgo(dateStr) {
  if (!dateStr) return 'recently';
  const diff = Date.now() - new Date(dateStr).getTime();
  const mins = Math.floor(diff / 60000);
  if (mins < 1)  return 'just now';
  if (mins < 60) return `${mins} min${mins !== 1 ? 's' : ''} ago`;
  const hrs = Math.floor(mins / 60);
  if (hrs < 24)  return `${hrs} hour${hrs !== 1 ? 's' : ''} ago`;
  return `${Math.floor(hrs / 24)} day${Math.floor(hrs / 24) !== 1 ? 's' : ''} ago`;
}
